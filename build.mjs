// Builds dist/ from tokens/ and components/. Run: node build.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const t = JSON.parse(readFileSync('tokens/tokens.json', 'utf8'));
const out = [`/* DMWorks tokens v${t.version} — generated by build.mjs, edit tokens/tokens.json */`];

// Colour themes: dark is the default, the rest switch on [data-theme].
const ref = (v) => v.replace(/^\{(.+)\}$/, 'var(--$1)');
for (const theme of t.color.themes) {
  const sel = theme.id === 'dark' ? ':root, [data-theme="dark"]' : `[data-theme="${theme.id}"]`;
  const scheme = theme.id === 'light' ? 'light' : 'dark';
  out.push(`${sel} {\n  color-scheme: ${scheme};\n` +
    t.color.tokens.map((c) => `  --${c.name}: ${ref(c.value[theme.id] ?? c.value.dark)};`).join('\n') + '\n}');
}
out.push('/* Product option: warnings in yellow, for products without yellow actions (DMWorks Net). */\n[data-warning="yellow"] { --warning: var(--create); }');

const scale = [];
for (const group of ['spacing', 'radius', 'size', 'stroke']) for (const s of t[group].tokens) scale.push(`  --${s.name}: ${s.value};`);
scale.push(`  --font-sans: ${t.type.families.sans};`, `  --font-mono: ${t.type.families.mono};`);
for (const g of t.type.groups) for (const s of g.styles)
  scale.push(`  --text-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${g.family});`);
out.push(`:root {\n${scale.join('\n')}\n}`);
const tokens = out.join('\n\n') + '\n';

const cat = (dir) => readdirSync(dir).filter((f) => f.endsWith('.css')).sort()
  .map((f) => `/* ${join(dir, f)} */\n` + readFileSync(join(dir, f), 'utf8')).join('\n');

rmSync('dist', { recursive: true, force: true });
mkdirSync('dist/apps', { recursive: true });
writeFileSync('dist/tokens.css', tokens);
writeFileSync('dist/dmworks.css', tokens + '\n' + cat('components/core'));
for (const app of readdirSync('components/apps')) writeFileSync(`dist/apps/${app}.css`, cat(join('components/apps', app)));
console.log('dist/ built:', readdirSync('dist'), readdirSync('dist/apps'));
